const assert = require('assert');
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const source = path.join(__dirname, '../web/calendar-view.js');
assert.ok(fs.existsSync(source), 'CalendarView must exist');
const c = {window:{}, Date, Intl};
vm.runInNewContext(fs.readFileSync(source, 'utf8'),c);
const view = c.window.CalendarView;
const data = {meals:[{date:'2026-11-01',lunch:'Rice',dinner:'Soup'},{date:'2026-11-02'},{date:'2026-11-03',dinner:'Fish'}],eventDates:['2026-11-01','2026-11-04'],upcomingEvents:[{date:'2026-11-05',title:'Third',start:'2026-11-05T15:00:00Z',allDay:false},{date:'2026-11-02',title:'Past',start:'2026-11-02T11:00:00Z',allDay:false},{date:'2026-11-03',title:'First',allDay:true},{date:'2026-11-04',title:'Second',start:'2026-11-04T12:00:00Z',allDay:false}]};
let grid = view.render(data,'2026-11-01',new Date('2026-11-01T15:00:00Z'));
assert.strictEqual(grid.cells.length,42);
assert.strictEqual(grid.cells[0].date,'2026-10-26');
assert.strictEqual(grid.cells[6].date,'2026-11-01');
assert.strictEqual(grid.cells[6].today,true);
assert.strictEqual(grid.cells[6].meal,true);
assert.strictEqual(grid.cells[6].event,true);
assert.strictEqual(grid.cells[7].meal,false);
assert.strictEqual(grid.cells[8].meal,true);
assert.strictEqual(grid.cells[9].event,true);
assert.strictEqual(view.currentMeal(data,new Date('2026-11-01T14:59:00Z')).title,'Rice');
assert.strictEqual(view.currentMeal(data,new Date('2026-11-01T15:00:00Z')).title,'Soup');
assert.strictEqual(view.currentMeal(data,new Date('2026-11-01T21:00:00Z')),null);
assert.strictEqual(view.currentMeal(data,new Date('2026-11-02T14:00:00Z')),null);
assert.strictEqual(view.currentMeal(data,new Date('2026-11-02T02:59:00Z')),null);
assert.deepStrictEqual(Array.from(view.upcomingEvents(data,new Date('2026-11-02T12:00:00Z'),3), x=>x.title),['First','Second','Third']);
assert.deepStrictEqual(Array.from(view.upcomingEvents(data,new Date('2026-11-03T22:00:00Z'),3), x=>x.title),['First','Second','Third']);
assert.strictEqual(view.render(null,'2024-02-15',new Date('2024-02-15T12:00:00Z')).cells.length,42);
assert.strictEqual(view.render(null,'2024-02-15',new Date('2024-02-15T12:00:00Z')).cells.filter(x=>x.date==='2024-02-29').length,1);
console.log('CalendarView checks passed');
